"""Generate chaos-only recipes and sealed results from a pinned recipe snapshot."""
import argparse
import copy
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BP = ROOT / "kit_crafting_bp"
TAG = "kit_crafting_chaos"
KINDS = ("minecraft:recipe_shaped", "minecraft:recipe_shapeless")


def encoded(value):
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def crafting_recipe(document):
    for kind in KINDS:
        if kind in document and "crafting_table" in document[kind].get("tags", []):
            return kind, document[kind]
    return None


def generate():
    snapshot = json.loads((ROOT / "data/vanilla_crafting_recipes.json").read_text())
    documents = snapshot["recipes"].copy()
    # Local definitions win over a vanilla recipe with the same identifier.
    for path in sorted((BP / "recipes").glob("*.json")):
        document = json.loads(path.read_text())
        found = crafting_recipe(document)
        if found:
            documents[found[1]["description"]["identifier"]] = document

    files = {}
    rewards = {}
    for identifier, document in sorted(documents.items()):
        kind, recipe = crafting_recipe(document)
        results = recipe["result"]
        primary = results[0] if isinstance(results, list) else results
        primary = {"item": primary} if isinstance(primary, str) else primary.copy()
        if ":" not in primary["item"]:
            primary["item"] = "minecraft:" + primary["item"]
        primary.setdefault("count", 1)
        primary.setdefault("data", 0)
        assert set(primary) == {"item", "count", "data"}, primary
        assert 1 <= primary["count"] <= 64, primary
        digest = hashlib.sha256(json.dumps(primary, sort_keys=True).encode()).hexdigest()[:16]
        token = f"kit_crafting:chaos_result_{digest}"
        loot_path = f"kit_crafting/chaos/normal_{digest}"
        rewards[token] = {**primary, "loot": loot_path}
        cloned = copy.deepcopy(document)
        cloned[kind]["description"]["identifier"] = "kit_crafting:chaos_" + identifier.replace(":", "_")
        cloned[kind]["tags"] = [TAG]
        replacement = {"item": token, "count": 1}
        # Buckets/bottles are returned on both branches, just like normal crafting.
        cloned[kind]["result"] = [replacement, *results[1:]] if isinstance(results, list) else replacement
        files[BP / "recipes/chaos" / (identifier.replace(":", "_") + ".json")] = encoded(cloned)
        files[BP / "items/chaos" / (digest + ".json")] = encoded({
            "format_version": "1.20.50",
            "minecraft:item": {
                "description": {"identifier": token},
                "components": {
                    "minecraft:display_name": {"value": "item.kit_crafting:chaos_result.name"},
                    "minecraft:icon": {"texture": "kit_crafting_chaos_result"},
                    "minecraft:max_stack_size": 1,
                },
            },
        })
        files[BP / "loot_tables" / (loot_path + ".json")] = encoded({
            "pools": [{"rolls": 1, "entries": [{
                "type": "item", "name": primary["item"], "functions": [
                    {"function": "set_data", "data": primary["data"]},
                    {"function": "set_count", "count": primary["count"]},
                ],
            }]}],
        })
    files[BP / "scripts/chaos_rewards.js"] = "// Generated by scripts/generate_chaos.py; do not edit.\nexport const REWARDS = " + encoded(rewards).rstrip() + ";\n"
    return files, len(documents), len(rewards)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, recipes, rewards = generate()
    directories = [BP / "recipes/chaos", BP / "items/chaos", BP / "loot_tables/kit_crafting/chaos"]
    existing = {p for directory in directories for p in directory.glob("*.json")}
    stale = existing - files.keys()
    changed = [p for p, content in files.items() if not p.exists() or p.read_text() != content]
    if args.check:
        if stale or changed:
            raise SystemExit("Chaos data is stale. Run make chaos after editing recipes.")
    else:
        for path in stale:
            path.unlink()
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(files[path])
    print(f"Chaos data: {recipes} recipes, {rewards} reward types ({'verified' if args.check else 'generated'})")


if __name__ == "__main__":
    main()
